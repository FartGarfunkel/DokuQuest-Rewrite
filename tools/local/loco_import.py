#!/usr/bin/env python3
"""Epic Fight's (Soulrend) idle, walk and run loops sampled into our rig's angles -> src/render/loco_poses_data.inc.
Needs the extracted Epic Fight animations and efpose.py (the joint maths) on EF_DIR. Walk and run are aligned so the right
leg is fully forward at a quarter of the cycle (our walk phase pi/2, where sin peaks); idle runs on its own clock."""
import os, sys
EF_DIR = os.environ.get("EF_DIR", os.path.expanduser("~/.hermes/profiles/claudebot/cache/scratch/ef"))
sys.path.insert(0, EF_DIR)
import efpose as e
OUT = os.path.join(os.path.dirname(__file__), "..", "..", "src", "render", "loco_poses_data.inc")
PARTS = ["body", "head", "armR", "foreR", "armL", "foreL", "legR", "shinR", "legL", "shinL"]
K = 32
def frames(name, cyc):
    tr = e.load_anim(name); T = e.length(tr)
    off = 0.0
    if cyc:   # where the right leg is furthest forward
        best = max(range(96), key=lambda i: e.charangles(e.pose_at(tr, T * i / 96))["legR"][0])
        off = T * best / 96 - T * 0.25
    rows = []
    for i in range(K):
        t = (off + T * i / K) % T
        o = e.charangles(e.pose_at(tr, t))
        vals = []
        for p in PARTS: vals += [float(v) for v in o[p]]
        vals.append(float(o["lift"]))
        rows.append(vals)
    # the stance's standing turn (Epic Fight's idle stands a third turned, the head looking back ahead): taken out, so the
    # body faces where it walks; the swing about it stays. body y at 1, head y at 4, the legs' y at 19 and 25
    y0 = sum(r[1] for r in rows) / len(rows)
    for r in rows:
        r[1] -= y0; r[4] += y0; r[19] -= y0; r[25] -= y0
    return T, rows
L = ["// generated by tools/local/loco_import.py from Epic Fight's living/idle, walk, run (Soulrend): do not edit",
     "// %d frames per loop: body head armR foreR armL foreL legR shinR legL shinL (x y z each), lift" % K]
for nm, clip, cyc in (("IDLE", "living/idle", False), ("WALK", "living/walk", True), ("RUN", "living/run", True)):
    T, rows = frames(clip, cyc)
    L.append("static const float LOCO_%s_LEN = %.4ff;" % (nm, T))
    L.append("static const float LOCO_%s[%d][31] = {" % (nm, K))
    for r in rows: L.append("  {" + ",".join("%.4ff" % v for v in r) + "},")
    L.append("};")
open(OUT, "w").write("\n".join(L) + "\n")
print("wrote", OUT)
