#!/usr/bin/env python3
"""Extract the structure generators' data tables from the original game (loot tables, village/town styles,
dungeon themes, decor lists, lore keys...) and write them into src/gen/structures_data.cpp as JSON.

  python3 tools/port/structdata.py <js-source-root>

The tables are taken after every module has loaded (so later additions, like the treasure maps seas.js puts
in the wreck and temple chests, and the filtering against the blocks and items the game has, are included).
"""
import json, subprocess, sys, pathlib, tempfile

EXPR = r"""(() => {
  const strip = (o) => { const r = {}; for (const k of Object.keys(o)) if (typeof o[k] !== 'function') r[k] = o[k]; return r; };
  const td = {}; for (const k of Object.keys(TOWN_DECOR)) td[k] = townDecor(k);
  const dth = {}; for (const k of Object.keys(DTHEME)) dth[k] = strip(DTHEME[k]);
  const vt = {}; for (const k of Object.keys(TOWN_VT)) vt[k] = [TOWN_VT[k].W, TOWN_VT[k].D, TOWN_VT[k].H];
  return { STRUCT_LOOT, DUNGEON_LOOT, LORE_KEYS, VSTYLE, TOWN_PAVE, TOWN_DECOR: td, DTHEME: dth, DH_THEMES, TOWN_TIERS,
    VFLOWERS, VSYL, JOB_STATION, WORKSHOP_JOBS, RUIN_PAL, TOWN_VT: vt };
})()"""

# game/villages.js vLoot (a table local to the function)
VLOOT = {
  'house': [['bread', 1, 4, 0.6], ['apple', 1, 3, 0.5], ['wheat_seeds', 2, 6, 0.4], ['emerald', 1, 2, 0.25], ['torch', 2, 6, 0.4], ['potato', 1, 4, 0.3], ['carrot', 1, 3, 0.3], ['stick', 2, 5, 0.3]],
  'smithy': [['iron_ingot', 1, 4, 0.7], ['coal', 2, 6, 0.6], ['bread', 1, 3, 0.4], ['iron_pickaxe', 1, 1, 0.2], ['iron_sword', 1, 1, 0.15], ['silver_ingot', 1, 2, 0.25], ['steel_ingot', 1, 1, 0.12], ['emerald', 1, 3, 0.3], ['iron_helmet', 1, 1, 0.12]],
  'library': [['book', 1, 3, 0.7], ['paper', 2, 6, 0.6], ['feather', 1, 3, 0.4], ['emerald', 1, 2, 0.3], ['empty_map', 1, 1, 0.2], ['compass', 1, 1, 0.15]],
  'tavern': [['bread', 2, 5, 0.7], ['cooked_beef', 1, 3, 0.4], ['apple', 1, 4, 0.5], ['honey_bottle', 1, 2, 0.3], ['emerald', 1, 3, 0.4], ['cake', 1, 1, 0.15]],
}

def main():
    if len(sys.argv) < 2: print(__doc__); sys.exit(1)
    here = pathlib.Path(__file__).resolve().parent
    out = here.parent.parent / 'src/gen/structures_data.cpp'
    with tempfile.TemporaryDirectory() as td:
        f = pathlib.Path(td) / 'd.json'
        subprocess.run([sys.executable, str(here / 'jsdump.py'), sys.argv[1], str(f), EXPR], check=True)
        data = json.loads(f.read_text())
    data['VLOOT'] = VLOOT
    text = json.dumps(data, separators=(',', ':'))
    parts = [text[i:i + 8000] for i in range(0, len(text), 8000)]
    body = '\n'.join('R"DQJSON(' + p + ')DQJSON"' for p in parts)
    out.write_text('// gen/structures_data.cpp — GENERATED by tools/port/structdata.py from the original game: loot tables,\n'
                   '// village/town styles, dungeon themes, decor lists, lore keys. Do not edit by hand.\n'
                   '#include "gen/structures_common.h"\n\nnamespace dq {\nconst char* structureDataJson() {\n  return\n' + body + ';\n}\n} // namespace dq\n')
    print('wrote', out, len(text), 'bytes of JSON')

if __name__ == '__main__': main()
