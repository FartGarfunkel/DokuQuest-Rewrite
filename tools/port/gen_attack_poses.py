#!/usr/bin/env python3
"""tools/port/gen_attack_poses.py — the attack moves' drawn poses (render/attack_poses.cpp) from the fit of our own rig's
angles to the measured swings (the study scripts outside the repo: fitarms.py -> fit_keys.json). Writes
src/render/attack_poses_data.inc: per move, its keys in seconds from the strike's wind-up (the move table's hitFrom is
that plus the blend in from the stance): body pitch and turn, the hips' lift, the legs, the striking arm (arm x y z,
forearm, the grip's turn x z) and the other arm (arm x y z, forearm)."""
import json, os, sys
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.expanduser('~/.hermes/profiles/claudebot/cache/scratch/ef/fit_keys.json')
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), 'src', 'render', 'attack_poses_data.inc')
D = json.load(open(SRC))
ORDER = ['sword1', 'sword2', 'sword3', 'sword_dash', 'sword_air', 'dagger1', 'dagger2', 'dagger3', 'axe1', 'axe2', 'fist1', 'fist2', 'fist3', 'tool1', 'tool1']
r = lambda v: '%.3ff' % v
lines = ['// generated by tools/port/gen_attack_poses.py (our rig fitted to measured swings; rounded): do not edit by hand', '']
for i, name in enumerate(ORDER):
    m = D[name]
    lines.append('static const AtkKey K_%d[] = {   // %s' % (i, name))
    for row in m['rows']:
        vals = [row['t'], row['body'][0], row['body'][1], row['lift']] + row['legs'] + row['act'] + row['oth']
        lines.append('  {' + ', '.join(r(v) for v in vals) + '},')
    lines.append('};')
lines.append('static const AtkClip CLIPS[] = {')
for i, name in enumerate(ORDER):
    m = D[name]
    lines.append('  {K_%d, %d, %s, %s},   // %s' % (i, len(m['rows']), 'true' if m['left'] else 'false', r(m['pre']), name))
lines.append('};')
open(OUT, 'w').write('\n'.join(lines) + '\n')
print('wrote', OUT, len(ORDER), 'moves')
