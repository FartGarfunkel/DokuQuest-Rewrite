"""Turns dq_data.json (from extract.py, run on the JS 0.9.0.90 source) into the Rust data files.
   python3 tools/port/extract.py <DokuQuest-0.9.0.90 dir> dq_data.json && python3 tools/port/gen.py dq_data.json"""
import json, sys, re, base64, pathlib
d = json.load(open(sys.argv[1])); root = pathlib.Path(__file__).resolve().parents[2] / 'crates/common_server'
B = sorted(d['blocks'], key=lambda b: b['id']); I = d['items']; T = d['tiles']; FACES = d['faces']; PIX = base64.b64decode(d['pix'])
SK = d['shapes']; bykey = {b['key']: b for b in B}
used, remap = [], {}
def tile(old):
    if old is None: return 65535
    if old not in remap: remap[old] = len(used); used.append(old)
    return remap[old]
def tname(n): return tile(T.get(n)) if isinstance(n, str) else 65535
def s(x): return json.dumps(x or '', ensure_ascii=False)
def const(k): c = re.sub(r'[^A-Z0-9]', '_', k.upper()); return ('B_' + c) if c[0].isdigit() else c
BOX = {0: (0,0,0,16,16,16), 1: (0,0,0,16,8,16), 2: (0,0,0,16,8,16), 3: (6,0,6,10,16,10), 4: (0,0,7,16,15,9), 5: (4,0,4,12,14,12), 6: (0,0,7,16,16,9),
       7: (0,0,13,16,16,16), 8: (0,0,0,16,3,16), 9: (0,0,15,16,16,16), 10: (0,0,0,16,1,16), 11: (0,0,0,16,9,16), 12: (0,0,0,16,2,16), 13: (7,0,7,9,6,9),
       14: (1,0,1,15,8,15), 15: (7,0,7,9,16,9), 17: (0,0,0,16,15,16), 18: (2,2,15,14,14,16), 20: (5,4,5,11,12,11), 21: (0,0,0,16,1,16), 22: (0,0,0,16,1,16),
       23: (6,0,5,10,8,11), 24: (5,0,6,11,2,10), 25: (1,0,1,15,1,15), 26: (0,0,0,16,2,16), 27: (0,0,0,16,2,16), 28: (0,0,0,16,1,16), 30: (0,0,0,16,16,4),
       31: (0,10,0,16,16,16), 32: (0,0,0,16,6,16), 33: (6,0,6,10,8,10), 34: (0,1,0,16,2,16), 35: (1,0,1,15,16,15), 36: (4,0,4,12,16,12), 37: (7,0,7,9,10,9), 38: (1,0,1,15,15,15), 39: (13,0,0,16,16,16), 40: (0,0,13,16,16,16), 41: (0,0,7,2,15,9)}
TOOL = {'pickaxe': 1, 'axe': 2, 'shovel': 3}
rows, ids, extra = [], [], []
for b in B:
    r = b['render']; k = b['key']
    kind = 'Air' if k == 'air' else 'Hidden' if r == 0 else 'Liquid' if r == 4 else 'Plant' if r == 3 else 'Solid' if r in (1, 2) else 'Shape'
    shape = (b.get('shapeKind') or 0) if r == 7 else 37 if r == 5 else 38 if r == 6 else 0
    opaque = kind == 'Solid' and bool(b.get('opaque') or b.get('isLeaves'))
    f = [tile(x) for x in (FACES[b['id']] or [0]*6)]
    tint = {'grass': 1, 'foliage': 2}.get(b.get('tint'), 0)
    drop = '-' if b.get('drop') == '' else (b.get('drop') or '')
    row = lambda key, name, shp, solid, drp: f'    BlockDef {{ key: {s(key)}, name: {s(name)}, kind: {kind}, opaque: {str(opaque).lower()}, solid: {str(solid).lower()}, hardness: {float(b.get("hardness") or 0)}, tool: {TOOL.get(b.get("tool"), 0)}, tier: {int(b.get("tier") or 0)}, drop: {s(drp)}, light: {int(b.get("light") or 0)}, shape: {shp}, tint: {tint}, falls: {str(bool(b.get("falls"))).lower()}, sound: {s(b.get("sound") or "stone")}, faces: {f} }},'
    rows.append(row(k, b['name'], shape, bool(b['solid']), drop))
    ids.append(f'    pub const {const(k)}: u16 = {b["id"]};')
    if r == 7 and shape in (4, 7, 8): extra.append((row(k + '_open', b['name'], {4: 41, 7: 39, 8: 40}[shape], False, drop or k), k + '_open'))
for i, (rw, key) in enumerate(extra): rows.append(rw); ids.append(f'    pub const {const(key)}: u16 = {len(B) + i};')
ids += ['    pub const SNOW: u16 = SNOWY_GRASS;', '    pub const RED_FLOWER: u16 = FLOWER_RED;', '    pub const YELLOW_FLOWER: u16 = FLOWER_YELLOW;']
boxes = ', '.join(str(list(BOX.get(i, BOX[0]))) for i in range(42))
(root/'src/gen_blocks.rs').write_text('// @generated by tools/port/gen.py from DokuQuest 0.9.0.90 — do not edit by hand.\nuse crate::blocks::{BlockDef, Kind::*};\n\npub static BLOCKS: &[BlockDef] = &[\n' + '\n'.join(rows) +
    f'\n];\n\n/// Box (in 1/16 block) per shape id: 0 = full cube, 1..=36 JS SHAPE_KIND, 37 torch, 38 model, 39-41 open door/trapdoor/gate.\npub static SHAPE_BOXES: [[u8; 6]; 42] = [{boxes}];\n\n#[allow(dead_code)]\npub mod id {{\n' + '\n'.join(ids) + '\n}\n')
def icon(it):
    ic = it.get('icon') or it['key']
    if ic.startswith('block:'): bb = bykey.get(ic[6:]); return tile((FACES[bb['id']] or [None])[0]) if bb else 65535
    return tname(ic)
L = []
for k, it in I.items():
    t, fo, ar = it.get('tool') or {}, it.get('food') or {}, it.get('armor') or {}
    blk = bykey[it['block']]['id'] if it.get('block') in bykey else -1
    L.append('\t'.join(map(str, [k, it.get('name', k), it.get('maxStack', 64), icon(it), blk, t.get('type', ''), t.get('tier', 0), t.get('speed', 1), t.get('damage', 1), t.get('durability', 0), fo.get('heal', 0), ar.get('slot', -1), ar.get('points', 0)])))
(root/'data/items.tsv').write_text('\n'.join(L) + '\n')
def cellv(v): return '|'.join(v) if isinstance(v, list) else (v or '')
R = []
for r in d['recipes']:
    if r.get('shape'):
        sh = r['shape']; w = max(len(x) for x in sh); km = r.get('key') or {}
        cells = [cellv(km.get(row[i])) if i < len(row) and row[i] != ' ' else '' for row in sh for i in range(w)]
        R.append('\t'.join([r['out'], str(r.get('n', 1)), str(w), str(len(sh)), ','.join(cells)]))
    elif r.get('items'): R.append('\t'.join([r['out'], str(r.get('n', 1)), '0', '0', ','.join(cellv(x) for x in r['items'])]))
(root/'data/recipes.tsv').write_text('\n'.join(R) + '\n')
(root/'data/tags.tsv').write_text(''.join(f'{t}\t{",".join(m)}\n' for t, m in d['tags'].items()))
(root/'data/smelting.tsv').write_text(''.join(f'{a}\t{b}\n' for a, b in d['smelting'].items() if isinstance(b, str)))
FL = ['swims', 'water', 'flyer', 'fly', 'floaty', 'nocturnal', 'fleesSun', 'undead', 'fireImmune', 'boss', 'skittish', 'prey', 'retaliates', 'grazer', 'herd', 'hopper',
      'climber', 'ambient', 'npc', 'golem', 'angersWhenHurt', 'dayNeutral', 'ranged', 'guard', 'needsAir']
M = []
for k, m in d['mobs'].items():
    dr = ';'.join(':'.join(str(x) for x in (list(e) + [1, 1, 1])[:4]) for e in (m.get('drops') or []) if isinstance(e, list))
    M.append('\t'.join(map(str, [k, m.get('label') or k.replace('_', ' ').title(), m.get('model', k), m.get('hp', 10), m.get('w', 0.6), m.get('h', 1.8), m.get('speed', 1),
        m.get('damage', 0), int(bool(m.get('hostile'))), ','.join(f for f in FL if m.get(f)), dr, m.get('xp', 0)])))
(root/'data/mobs.tsv').write_text('\n'.join(M) + '\n')
def texspec(t):
    if not isinstance(t, dict): a = tname(t); return [a] * 6
    a = t.get('all'); g = lambda *ks: next((t[x] for x in ks if t.get(x)), a)
    return [tname(g('right', 'side')), tname(g('left', 'side')), tname(g('top')), tname(g('bottom')), tname(g('back')), tname(g('front'))]
P = []
for k, md in d['models'].items():
    if not md or not md.get('parts'): continue
    P.append(f'M\t{k}\t{md.get("scale", 1)}')
    for p in md['parts']:
        v = lambda a: ','.join(f'{x:g}' for x in a)
        P.append('\t'.join(['P', p['name'], p.get('parent') or '-', v(p['pivot']), v(p['min']), v(p['max']), p.get('limb') or p.get('role') or '-', str(p.get('side', 0)), str(int(bool(p.get('front')))), ','.join(map(str, texspec(p.get('tex'))))]))
(root/'data/models.tsv').write_text('\n'.join(P) + '\n')
PM = [f'{remap[T[n]]}\t{",".join(bc)}\t{",".join(ic)}' for n, bc, ic in (d.get('packc') or []) if T.get(n) in remap]
(root/'data/packmap.tsv').write_text('\n'.join(PM) + '\n')
(root/'data/tiles.bin').write_bytes(b''.join(PIX[o * 1024:(o + 1) * 1024] for o in used))
print(f'blocks {len(B)} items {len(L)} recipes {len(R)} mobs {len(M)} model lines {len(P)} tiles {len(used)}')
